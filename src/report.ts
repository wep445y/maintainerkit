export type ActivityKind = "issue" | "pull_request";

export interface DigestEntry {
  number: number;
  title: string;
  url: string;
  updatedAt: string;
  author: string;
  labels: string[];
  kind: ActivityKind;
}

export interface MergedPullRequest extends DigestEntry {
  kind: "pull_request";
  mergedAt: string;
}

const markdownSpecialCharacters = new Set(["\\", "`", "*", "_", "{", "}", "[", "]", "(", ")", "#", "+", "-", ".", "!", "|", ">", "<", "&", "~"]);

function escapeMarkdown(value: string): string {
  return [...value.replace(/[\r\n\t]+/g, " ")]
    .map((character) => markdownSpecialCharacters.has(character) ? `\\${character}` : character)
    .join("");
}

function day(value: string): string {
  return value.slice(0, 10);
}

function sortedByDate<T extends { updatedAt: string }>(items: T[]): T[] {
  return [...items].sort((a, b) => Date.parse(b.updatedAt) - Date.parse(a.updatedAt));
}

export function buildDigest(
  entries: DigestEntry[],
  options: { repository: string; title: string; since: string; maxItems: number },
): string {
  const sorted = sortedByDate(entries);
  const shown = sorted.slice(0, options.maxItems);
  const issues = shown.filter((entry) => entry.kind === "issue");
  const pullRequests = shown.filter((entry) => entry.kind === "pull_request");
  const issueTotal = entries.filter((entry) => entry.kind === "issue").length;
  const pullRequestTotal = entries.filter((entry) => entry.kind === "pull_request").length;
  const lines = [
    `# ${escapeMarkdown(options.title)}`,
    "",
    `Repository: [${escapeMarkdown(options.repository)}](https://github.com/${options.repository})  `,
    `Window: ${day(options.since)} through the workflow run date  `,
    `Activity found: ${issueTotal} issue(s), ${pullRequestTotal} pull request(s).`,
    "",
  ];

  const addSection = (heading: string, section: DigestEntry[], total: number): void => {
    lines.push(`## ${heading} (${total})`, "");
    if (section.length === 0) {
      lines.push("_No matching activity._", "");
      return;
    }
    for (const entry of section) {
      const labels = entry.labels.length ? ` — ${entry.labels.map(escapeMarkdown).join(", ")}` : "";
      lines.push(
        `- [#${entry.number} ${escapeMarkdown(entry.title)}](${entry.url}) — @${escapeMarkdown(entry.author)} — updated ${day(entry.updatedAt)}${labels}`,
      );
    }
    lines.push("");
  };

  addSection("Issues", issues, issueTotal);
  addSection("Pull requests", pullRequests, pullRequestTotal);
  if (sorted.length > shown.length) {
    lines.push(`_Showing the latest ${shown.length} of ${sorted.length} activity items._`, "");
  }
  lines.push("---", "_Generated by [MaintainerKit](https://github.com/wep445y/maintainerkit). Review before sharing or acting on this digest._");
  return lines.join("\n");
}

export function buildReleaseNotes(
  pullRequests: MergedPullRequest[],
  options: { repository: string; since: string },
): string {
  const sorted = [...pullRequests].sort((a, b) => Date.parse(b.mergedAt) - Date.parse(a.mergedAt));
  const lines = [
    `# Draft release notes — ${escapeMarkdown(options.repository)}`,
    "",
    `Merged since ${day(options.since)}. This is a draft; review and edit it before publishing.`,
    "",
  ];

  if (sorted.length === 0) {
    lines.push("_No merged pull requests found in this window._");
    return lines.join("\n");
  }

  const groups = new Map<string, MergedPullRequest[]>();
  for (const pullRequest of sorted) {
    const category = pullRequest.labels.find((label) => !label.toLowerCase().startsWith("cla")) ?? "Other changes";
    const group = groups.get(category) ?? [];
    group.push(pullRequest);
    groups.set(category, group);
  }

  for (const [category, group] of groups) {
    lines.push(`## ${escapeMarkdown(category)}`, "");
    for (const pullRequest of group) {
      lines.push(`- ${escapeMarkdown(pullRequest.title)} ([#${pullRequest.number}](${pullRequest.url}))`);
    }
    lines.push("");
  }
  lines.push("---", "_Generated by [MaintainerKit](https://github.com/wep445y/maintainerkit). No release was created or published._");
  return lines.join("\n");
}
